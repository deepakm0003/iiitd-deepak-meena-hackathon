"""Tracked company universe.

config/universe_seed.yaml (hand-curated: ticker, sector, aliases) + SEC data (OBSERVED: CIK, legal name, SIC)
-> config/universe.yaml, which every collector and the entity linker read.
"""

import re
from dataclasses import dataclass
from datetime import UTC, datetime
from pathlib import Path

import yaml

from tripwire.config import load_yaml
from tripwire.settings import CONFIG_DIR

SEC_TICKERS_URL = "https://www.sec.gov/files/company_tickers.json"
SEC_SUBMISSIONS_URL = "https://data.sec.gov/submissions/CIK{cik:010d}.json"


@dataclass(frozen=True)
class Company:
    ticker: str
    sector: str
    aliases: tuple[str, ...]
    cik: int | None = None
    sec_name: str | None = None
    sic: str | None = None
    sic_description: str | None = None

    @property
    def all_names(self) -> tuple[str, ...]:
        """Aliases plus the SEC legal name, de-duplicated, longest first (longest match wins)."""
        seen: dict[str, str] = {}
        for name in (*self.aliases, *(n for n in (self.sec_name,) if n)):
            seen.setdefault(name.casefold(), name)
        return tuple(sorted(seen.values(), key=len, reverse=True))


def load_universe(config_dir: Path = CONFIG_DIR) -> list[Company]:
    data = load_yaml("universe.yaml", config_dir)
    companies = data.get("companies") or load_yaml("universe_seed.yaml", config_dir)["companies"]
    return [
        Company(
            ticker=c["ticker"],
            sector=c["sector"],
            aliases=tuple(c.get("aliases", [])),
            cik=c.get("cik"),
            sec_name=c.get("sec_name"),
            sic=c.get("sic"),
            sic_description=c.get("sic_description"),
        )
        for c in companies
    ]


def refresh_universe(http, config_dir: Path = CONFIG_DIR) -> list[dict]:
    """Fill SEC fields for every seed company and write config/universe.yaml."""
    seed = load_yaml("universe_seed.yaml", config_dir)["companies"]
    listing = http.get(SEC_TICKERS_URL).json()
    by_ticker = {row["ticker"].upper(): row for row in listing.values()}
    out, missing = [], []
    for company in seed:
        sec = by_ticker.get(company["ticker"].upper())
        if not sec:
            missing.append(company["ticker"])
            continue
        cik = int(sec["cik_str"])
        sub = http.get(SEC_SUBMISSIONS_URL.format(cik=cik)).json()
        out.append(
            {
                **company,
                "cik": cik,
                "sec_name": _tidy_legal_name(sub.get("name") or sec["title"]),
                "sic": sub.get("sic"),
                "sic_description": sub.get("sicDescription"),
            }
        )
    if missing:
        raise RuntimeError(f"tickers not found in SEC listing: {missing}")
    header = (
        "# GENERATED by `python -m tripwire universe --refresh` on "
        f"{datetime.now(UTC):%Y-%m-%d}. Edit universe_seed.yaml instead.\n"
        "# cik, sec_name, sic, sic_description: OBSERVED from SEC EDGAR. sector, aliases: curated.\n"
    )
    body = yaml.safe_dump({"companies": out}, sort_keys=False, allow_unicode=True, width=120)
    (config_dir / "universe.yaml").write_text(header + body, encoding="utf-8")
    return out


def _tidy_legal_name(name: str) -> str:
    """Keep SEC casing; only collapse whitespace and drop trailing suffixes like '/DE/' or '/NEW'."""
    name = re.sub(r"\s*/[A-Z]{2,4}/?\s*$", "", name.strip())
    return re.sub(r"\s+", " ", name)
