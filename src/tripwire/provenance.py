"""Provenance: every number Tripwire stores or shows says where it came from.

OBSERVED   real external data, unchanged (headlines, filing times, prices)
DERIVED    computed deterministically from a named dataset (merchant sector mix)
MODEL      output of a versioned ML model (sentiment, event class)
SYNTHETIC  generated by us to complete the book (loan maturity, swap notional)
ASSUMPTION a documented parameter we chose; must reference config/assumptions_register.yaml
MEASURED   an experimental result; must carry its sample size n
"""

import re
from enum import StrEnum
from typing import Generic, TypeVar

from pydantic import BaseModel, model_validator

T = TypeVar("T")
ASSUMPTION_ID = re.compile(r"^A-\d{2,}$")


class Provenance(StrEnum):
    OBSERVED = "OBSERVED"
    DERIVED = "DERIVED"
    MODEL = "MODEL"
    SYNTHETIC = "SYNTHETIC"
    ASSUMPTION = "ASSUMPTION"
    MEASURED = "MEASURED"


class Tagged(BaseModel, Generic[T]):
    """A value plus where it came from. Used in API payloads and the dashboard badges."""

    value: T
    provenance: Provenance
    source: str
    assumption_id: str | None = None
    n: int | None = None
    ci95: tuple[float, float] | None = None

    @model_validator(mode="after")
    def _check_rules(self) -> "Tagged[T]":
        if self.provenance is Provenance.ASSUMPTION and not (
            self.assumption_id and ASSUMPTION_ID.match(self.assumption_id)
        ):
            raise ValueError("ASSUMPTION values must reference an assumption id like 'A-07'")
        if self.provenance is Provenance.MEASURED and not (self.n and self.n > 0):
            raise ValueError("MEASURED values must carry their sample size n")
        return self
